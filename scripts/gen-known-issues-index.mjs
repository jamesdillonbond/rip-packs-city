#!/usr/bin/env node
/**
 * Regenerate the STATUS INDEX at the top of docs/reference/known-issues.md's
 * `### Open` section.
 *
 * WHY THIS EXISTS. The register is the canonical open list — CLAUDE.md and
 * docs/overnight/inbox/INDEX.md both say so — and it had grown to 47 numbered
 * items across ~80 KB of a single section with no way to see them at a glance.
 * 16 of them read RESOLVED / CLOSED / SHELVED / RETIRED in their own first
 * sentence while sitting under the heading `### Open`. That is not cosmetic:
 * item #8's own text records that it "sat under a Resolved heading, so anyone
 * enumerating the Open list never saw it" — the same confusion, pointed the
 * other way, cost that item several sessions.
 *
 * ⛔ WHY IT DOES NOT MOVE OR RENUMBER ANYTHING. Item numbers are stable
 * references: the ledger, focus.md, inbox filings, CLAUDE.md and migration
 * record files all cite "#22", "#38", "D8" by number. Re-sorting the section
 * would break every one of those citations, so the index is ADDITIVE — it maps
 * number → status → title and leaves the body untouched.
 *
 * ⚠ THE STATUS IS DERIVED FROM THE ITEM'S OWN FIRST SENTENCE, not from
 * judgement. That is deliberate: a derived label can be wrong only if the item's
 * own opening words are wrong, which is a defect worth surfacing anyway. Fix the
 * item's text, not the derivation.
 *
 * Usage: npm run docs:issues-index        (rewrites the block in place)
 *        npm run docs:issues-index -- --check   (exit 1 if stale; used by CI)
 */
import fs from "node:fs"
import { pathToFileURL } from "node:url"

const FILE = "docs/reference/known-issues.md"
const BEGIN = "<!-- BEGIN:ITEM-INDEX (generated by scripts/gen-known-issues-index.mjs — do not hand-edit) -->"
const END = "<!-- END:ITEM-INDEX -->"

/** An item heading: `12. ` or `3b. ` at line start, inside the Open section. */
const ITEM_RE = /^([0-9]+[a-z]?)\.\s+(.*)$/

/**
 * Status from the item's own opening words. Order matters: the first rule that
 * matches wins, and the "partial" rules are checked BEFORE the closed ones
 * because "PARTLY RESOLVED" contains "RESOLVED".
 */
export function deriveStatus(head) {
  const t = head.slice(0, 260).toUpperCase()
  if (/PARTLY|PARTIALLY|PARTIAL/.test(t)) return "partial"
  if (/RE-?OPENED|REGRESSED/.test(t)) return "open"
  if (/RESOLVED|CLOSED|RETIRED|SHELVED|\bDELETED\b|SUPERSEDED/.test(t)) return "closed"
  return "open"
}

/** The item's short title: its bolded lead, or the first clause. */
export function deriveTitle(head) {
  const bold = head.match(/\*\*(.+?)\*\*/)
  let t = bold ? bold[1] : head
  t = t.replace(/[`*]/g, "").replace(/\s+/g, " ").trim()
  const cut = t.search(/[—.:]\s/)
  if (cut > 24) t = t.slice(0, cut)
  return t.length > 96 ? t.slice(0, 95).trimEnd() + "…" : t
}

export function parseItems(md) {
  const lines = md.split("\n")
  const start = lines.findIndex((l) => l.startsWith("### Open"))
  if (start < 0) throw new Error("no '### Open' heading in " + FILE)
  let end = lines.findIndex((l, i) => i > start && /^### /.test(l))
  if (end < 0) end = lines.length
  const items = []
  for (let i = start; i < end; i++) {
    const m = lines[i].match(ITEM_RE)
    if (!m) continue
    items.push({ id: m[1], status: deriveStatus(m[2]), title: deriveTitle(m[2]), line: i + 1 })
  }
  return items
}

export function renderIndex(items) {
  const mark = { open: "🟡 open", partial: "🟠 partial", closed: "✅ closed" }
  const open = items.filter((i) => i.status === "open").length
  const partial = items.filter((i) => i.status === "partial").length
  const closed = items.filter((i) => i.status === "closed").length
  const rows = items.map((i) => `| **#${i.id}** | ${mark[i.status]} | ${i.title} |`).join("\n")
  return [
    BEGIN,
    "",
    `**STATUS INDEX — ${items.length} numbered items in this section: ${open} open · ${partial} partial · ${closed} closed.**`,
    "",
    "⚠ **Items are NEVER renumbered or re-sorted** — the ledger, `focus.md`, inbox filings, CLAUDE.md and",
    "migration record files all cite them by number, so a closed item keeps its slot rather than moving to",
    "`### Resolved`. **This index is how you skip the closed ones**, not a reason to move them.",
    "",
    "⚠ **Status is DERIVED from each item's own first sentence**, not from a curated list — so it cannot",
    "silently disagree with the item, and an index row that reads wrong means the ITEM's opening words are",
    "wrong. Fix the item, then re-run `npm run docs:issues-index`.",
    "⛔ **`closed` here means the item SAYS it is closed. It is not a re-verification** — read the item's own",
    "date stamp, and this file's standing rule that every recorded status has a shelf life.",
    "",
    "| item | status | what it is |",
    "|---|---|---|",
    rows,
    "",
    END,
  ].join("\n")
}

function main() {
  const check = process.argv.includes("--check")
  const md = fs.readFileSync(FILE, "utf8")
  const items = parseItems(md)
  if (items.length === 0) throw new Error("parsed ZERO items — refusing to write an empty index")
  const block = renderIndex(items)

  let out
  const b = md.indexOf(BEGIN)
  const e = md.indexOf(END)
  if (b >= 0 && e > b) {
    out = md.slice(0, b) + block + md.slice(e + END.length)
  } else {
    // First run: insert directly after the `### Open` heading and any stamp lines
    const lines = md.split("\n")
    const start = lines.findIndex((l) => l.startsWith("### Open"))
    let at = start + 1
    while (at < lines.length && (lines[at].startsWith(">") || lines[at].trim() === "")) at++
    lines.splice(at, 0, block, "")
    out = lines.join("\n")
  }

  if (check) {
    if (out !== md) {
      console.error(`known-issues index is STALE (${items.length} items parsed). Run: npm run docs:issues-index`)
      process.exit(1)
    }
    console.log(`known-issues index is current — ${items.length} items inspected`)
    return
  }
  fs.writeFileSync(FILE, out)
  console.log(`known-issues index written — ${items.length} items inspected`)
}

// ⚠ COMPARED AS A FILE URL, NOT A RAW PATH — and its failure mode is SILENT.
// `file://` + process.argv[1] is wrong on Windows: argv[1] is an OS path
// (C:\Users\...\gen-known-issues-index.mjs) while import.meta.url is always a URL
// (file:///C:/Users/.../gen-known-issues-index.mjs), so the two never match and main()
// NEVER RAN on the maintainer's own machine. Measured 2026-08-28: both
// `npm run docs:issues-index` (the WRITER) and `-- --check` (the GUARD) exited 0
// having done nothing and printed nothing — so a Windows session regenerating the
// index got a silent no-op, and the guard passed vacuously while CI, on Linux,
// stayed green. Same idiom and same reasoning as
// scripts/ingest-topshot-active-listings.mjs, which documents this trap already.
const isDirectRun =
  process.argv[1] != null && import.meta.url === pathToFileURL(process.argv[1]).href

if (isDirectRun) main()
