CREATE OR REPLACE FUNCTION public.editions_home_away_distinct()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
BEGIN
  -- A game has two teams. One team in both slots is a source defect (seen on the
  -- All Day and Top Shot chains and in an old backfill), never a fact: store neither.
  IF NEW.home_team IS NOT NULL AND NEW.home_team = NEW.away_team THEN
    NEW.home_team := NULL;
    NEW.away_team := NULL;
  END IF;
  RETURN NEW;
END;
$function$;
